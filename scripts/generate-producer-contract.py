#!/usr/bin/env python3
"""Emit the small shared field table, not a runtime schema engine."""
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from resmgrcheck.contracts import EVENT_FIELDS,EVENT_PRODUCERS
TYPES={'_word':'s','_runtime_device':'p','decimal':'d','_count':'n','_number':'i','_flag':'b','_facts':'f'}
rows=[]
for name,fields in EVENT_FIELDS.items():
    if EVENT_PRODUCERS[name] not in ('fixture','worker'):continue
    rows.append('    {"'+name+'","'+EVENT_PRODUCERS[name]+'","'+' '.join(fields)+'","'+''.join(TYPES[v.__name__] for v in fields.values())+'"},')
Path('native/common/producer_fields.h').write_text('/* Generated by scripts/generate-producer-contract.py. */\nstatic const struct field_spec producer_fields[]={\n'+'\n'.join(rows)+'\n};\n')
